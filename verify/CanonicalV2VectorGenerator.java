import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.security.MessageDigest;
import java.util.ArrayList;
import java.util.List;

import vehicle.fota.v1.Types;

/**
 * canonicalization-v2 normative test-vector bundle generator
 * (PAR-PROTO-DSN-CR-005 §5.3).
 *
 * Emits verify/inventory-canonical-v2/vectors.yaml: every vector carries input,
 * normalized (NFC + sorted) values, canonical_body.hex, digest_input.hex and
 * expected_digest.hex. The committed bundle is normative: Java and C++
 * implementations must pass every vector before release; release manifest
 * records the bundle SHA-256.
 *
 * Vector coverage (design §5.3): empty inventory, legacy single image,
 * structured SINGLE_IMAGE equivalence, A/B dual slot, mixed ECU, MULTI_TARGET,
 * input order permutation, NFC equivalence, slot absent/present, optional
 * active absent/false/true, and metadata (VIN/revision/timestamps) exclusion.
 */
public class CanonicalV2VectorGenerator {
  private static final Path OUT = Paths.get("verify/inventory-canonical-v2/vectors.yaml");

  public static void main(String[] args) throws Exception {
    StringBuilder yaml = new StringBuilder();
    yaml.append("# canonicalization-v2 normative test vectors (PAR-PROTO-DSN-CR-005 §5.3)\n");
    yaml.append("# AUTO-GENERATED by CanonicalV2VectorGenerator; do not hand-edit.\n");
    yaml.append("# domain / framing / digest are normative (design §5.2):\n");
    yaml.append("#   record  = uint8(field_id) || uint8(wire_kind) || uint32_be(len) || payload\n");
    yaml.append("#   digest_input = UTF8(domain) || 0x00 || canonical_body\n");
    yaml.append("#   digest = SHA-256(digest_input); value_hex = 64 lowercase hex\n");
    yaml.append("# Digest covers ONLY ECU hardware + normalized software units:\n");
    yaml.append("# VIN / inventory_revision / collectedAt / acceptedAt / envelope fields never\n");
    yaml.append("# enter digest_input (metadata exclusion vector v15).\n");
    yaml.append("domain: ").append(CanonicalV2.DOMAIN).append("\n");
    yaml.append("algorithm: ").append(CanonicalV2.ALGORITHM).append("\n");
    yaml.append("vectors:\n");

    List<Vector> vs = new ArrayList<>();
    // v01 empty inventory
    vs.add(new Vector("v01_empty", "empty inventory (no ECUs)", new ArrayList<>()));
    // v02 legacy single image (UNSPECIFIED, legacy fields only)
    List<Types.EcuVersion> legacy = new ArrayList<>();
    legacy.add(legacyEcu("ECU-ENGINE", "HW-1", "H1", "SW-1", "S1", null, null));
    vs.add(new Vector("v02_legacy_single_image", "legacy UNSPECIFIED single image (legacy fields only)", legacy));
    // v03 structured equivalent to v02 (MULTI_TARGET with one explicit ECU_IMAGE unit)
    // -> same canonical unit [ECU_IMAGE, SW-1, S1] -> same digest (design §5.1)
    List<Types.EcuVersion> structured = new ArrayList<>();
    structured.add(structuredEcu("ECU-ENGINE", "HW-1", "H1",
        Types.EcuSoftwareModel.ECU_SOFTWARE_MODEL_MULTI_TARGET,
        unit("ECU_IMAGE", "SW-1", "S1", null, true)));
    vs.add(new Vector("v03_structured_equivalent", "structured MULTI_TARGET single ECU_IMAGE unit equivalent to v02 (same digest)", structured));
    // v04 A/B dual slot: MULTI_TARGET, same target, two slots, one active (design §3.5)
    List<Types.EcuVersion> ab = new ArrayList<>();
    ab.add(structuredEcu("ECU-ENGINE", "HW-1", "H1",
        Types.EcuSoftwareModel.ECU_SOFTWARE_MODEL_MULTI_TARGET,
        unit("ECU_IMAGE", "SW-1", "S1", "slotA", true),
        unit("ECU_IMAGE", "SW-0", "S0", "slotB", false)));
    vs.add(new Vector("v04_ab_dual_slot", "A/B dual slot (MULTI_TARGET same target, exactly one active)", ab));
    // v05 mixed ECU (SINGLE_IMAGE legacy + MULTI_TARGET in one inventory)
    List<Types.EcuVersion> mixed = new ArrayList<>();
    mixed.add(legacyEcu("ECU-ENGINE", "HW-1", "H1", "SW-1", "S1", null, null));
    mixed.add(structuredEcu("ECU-GW", "HW-9", "H9",
        Types.EcuSoftwareModel.ECU_SOFTWARE_MODEL_MULTI_TARGET,
        unit("BODY", "PN-B", "VB", null, true),
        unit("GW", "PN-G", "VG", null, true)));
    vs.add(new Vector("v05_mixed_ecu", "mixed ECU: SINGLE_IMAGE + MULTI_TARGET", mixed));
    // v06 MULTI_TARGET 3 targets
    List<Types.EcuVersion> multi = new ArrayList<>();
    multi.add(structuredEcu("ECU-GW", "HW-9", "H9",
        Types.EcuSoftwareModel.ECU_SOFTWARE_MODEL_MULTI_TARGET,
        unit("BODY", "PN-B", "VB", null, true),
        unit("GW", "PN-G", "VG", null, true),
        unit("HPC", "PN-H", "VH", null, true)));
    vs.add(new Vector("v06_multi_target", "MULTI_TARGET with three targets", multi));
    // v07 permutation: same ECUs as v05, reversed input order -> same digest
    List<Types.EcuVersion> permuted = new ArrayList<>();
    permuted.add(mixed.get(1));
    permuted.add(mixed.get(0));
    vs.add(new Vector("v07_permutation", "input order permutation of v05 (same digest)", permuted));
    // v08/v09 NFC equivalence: "Café" composed vs decomposed part_number (legacy field 3)
    List<Types.EcuVersion> nfcA = new ArrayList<>();
    nfcA.add(legacyEcu("ECU-NFC", "HW-N", "HN", "Caf\u00e9", "S1", null, null));
    vs.add(new Vector("v08_nfc_composed", "part_number U+00E9 composed", nfcA));
    List<Types.EcuVersion> nfcB = new ArrayList<>();
    nfcB.add(legacyEcu("ECU-NFC", "HW-N", "HN", "Cafe\u0301", "S1", null, null));
    vs.add(new Vector("v09_nfc_decomposed", "part_number e+U+0301 decomposed (same digest as v08)", nfcB));
    // v10/v11 slot absent vs present (distinct digests)
    List<Types.EcuVersion> noSlot = new ArrayList<>();
    noSlot.add(structuredEcu("ECU-S", "HW-S", "HS",
        Types.EcuSoftwareModel.ECU_SOFTWARE_MODEL_MULTI_TARGET,
        unit("ECU_IMAGE", "SW-S", "SS", null, null)));
    vs.add(new Vector("v10_slot_absent", "unit without slot", noSlot));
    List<Types.EcuVersion> withSlot = new ArrayList<>();
    withSlot.add(structuredEcu("ECU-S", "HW-S", "HS",
        Types.EcuSoftwareModel.ECU_SOFTWARE_MODEL_MULTI_TARGET,
        unit("ECU_IMAGE", "SW-S", "SS", "slotA", null)));
    vs.add(new Vector("v11_slot_present", "same unit with slot slotA", withSlot));
    // v12/v13/v14 active absent / false / true (absent == true; false differs)
    List<Types.EcuVersion> actAbsent = new ArrayList<>();
    actAbsent.add(structuredEcu("ECU-A", "HW-A", "HA",
        Types.EcuSoftwareModel.ECU_SOFTWARE_MODEL_MULTI_TARGET,
        unit("ECU_IMAGE", "SW-A", "SA", null, null)));
    vs.add(new Vector("v12_active_absent", "active absent (normalizes to true)", actAbsent));
    List<Types.EcuVersion> actFalse = new ArrayList<>();
    actFalse.add(structuredEcu("ECU-A", "HW-A", "HA",
        Types.EcuSoftwareModel.ECU_SOFTWARE_MODEL_MULTI_TARGET,
        unit("ECU_IMAGE", "SW-A", "SA", null, false)));
    vs.add(new Vector("v13_active_false", "active=false (distinct digest)", actFalse));
    List<Types.EcuVersion> actTrue = new ArrayList<>();
    actTrue.add(structuredEcu("ECU-A", "HW-A", "HA",
        Types.EcuSoftwareModel.ECU_SOFTWARE_MODEL_MULTI_TARGET,
        unit("ECU_IMAGE", "SW-A", "SA", null, true)));
    vs.add(new Vector("v14_active_true", "active=true (same digest as v12)", actTrue));
    // v15 metadata exclusion: same inventory as v03; metadata is never an input
    vs.add(new Vector("v15_metadata_irrelevant",
        "same inventory as v03; VIN/revision/collectedAt/acceptedAt never enter digest_input (same digest)",
        structured));

    // compute + emit
    for (Vector v : vs) {
      CanonicalV2.CanonicalResult r = CanonicalV2.canonicalizeFromProto(v.ecus);
      yaml.append("  - id: ").append(v.id).append("\n");
      yaml.append("    description: ").append(v.desc).append("\n");
      yaml.append("    input_ecus:\n");
      if (v.ecus.isEmpty()) {
        yaml.append("      []\n");
      } else {
        for (Types.EcuVersion e : v.ecus) {
          yaml.append("      - ecu_id: ").append(yamlStr(e.getEcuId())).append("\n");
          yaml.append("        hardware_part_number: ").append(yamlStr(e.getHardwarePartNumber())).append("\n");
          yaml.append("        hw_version: ").append(yamlStr(e.getHwVersion())).append("\n");
          yaml.append("        software_model: ").append(e.getSoftwareModel().name()).append("\n");
          yaml.append("        legacy: {software_part_number: ").append(yamlStr(e.getSoftwarePartNumber()))
              .append(", sw_version: ").append(yamlStr(e.getSwVersion()))
              .append(", slot: ").append(e.hasSlot() ? yamlStr(e.getSlot()) : "null")
              .append(", active: ").append(e.hasActive() ? String.valueOf(e.getActive()) : "null")
              .append("}\n");
          yaml.append("        units:\n");
          for (Types.SoftwareUnitVersion u : e.getSoftwareUnitsList()) {
            yaml.append("          - target: ").append(yamlStr(u.getSoftwareTargetCode())).append("\n");
            yaml.append("            part_number: ").append(yamlStr(u.getSoftwarePartNumber())).append("\n");
            yaml.append("            version: ").append(yamlStr(u.getSwVersion())).append("\n");
            yaml.append("            slot: ").append(u.hasSlot() ? yamlStr(u.getSlot()) : "null").append("\n");
            yaml.append("            active: ").append(u.hasActive() ? String.valueOf(u.getActive()) : "null").append("\n");
          }
        }
      }
      yaml.append("    canonical_body_hex: ").append(hex(r.canonicalBody)).append("\n");
      yaml.append("    digest_input_hex: ").append(hex(r.digestInput)).append("\n");
      yaml.append("    expected_digest_hex: ").append(r.digestHex).append("\n");
    }

    Files.createDirectories(OUT.getParent());
    Files.write(OUT, yaml.toString().getBytes(StandardCharsets.UTF_8));
    byte[] bundleBytes = Files.readAllBytes(OUT);
    String bundleSha = sha256Hex(bundleBytes);
    System.out.println("wrote " + OUT + " (" + bundleBytes.length + " bytes)");
    System.out.println("bundle sha256 (vectors.yaml): " + bundleSha);
  }

  // ---- vector input builders ------------------------------------------------
  private static Types.EcuVersion legacyEcu(String ecuId, String hw, String hwv,
      String pn, String ver, String slot, Boolean active) {
    Types.EcuVersion.Builder b = Types.EcuVersion.newBuilder()
        .setEcuId(ecuId).setHardwarePartNumber(hw).setHwVersion(hwv)
        .setSoftwarePartNumber(pn).setSwVersion(ver)
        .setSoftwareModel(Types.EcuSoftwareModel.ECU_SOFTWARE_MODEL_UNSPECIFIED);
    if (slot != null) b.setSlot(slot);
    if (active != null) b.setActive(active);
    return b.build();
  }

  private static Types.EcuVersion structuredEcu(String ecuId, String hw, String hwv,
      Types.EcuSoftwareModel model, Types.SoftwareUnitVersion... units) {
    Types.EcuVersion.Builder b = Types.EcuVersion.newBuilder()
        .setEcuId(ecuId).setHardwarePartNumber(hw).setHwVersion(hwv)
        .setSoftwareModel(model);
    for (Types.SoftwareUnitVersion u : units) b.addSoftwareUnits(u);
    return b.build();
  }

  private static Types.SoftwareUnitVersion unit(String target, String pn, String ver,
      String slot, Boolean active) {
    Types.SoftwareUnitVersion.Builder b = Types.SoftwareUnitVersion.newBuilder()
        .setSoftwareTargetCode(target).setSoftwarePartNumber(pn).setSwVersion(ver);
    if (slot != null) b.setSlot(slot);
    if (active != null) b.setActive(active);
    return b.build();
  }

  private static final class Vector {
    final String id;
    final String desc;
    final List<Types.EcuVersion> ecus;
    Vector(String id, String desc, List<Types.EcuVersion> ecus) {
      this.id = id;
      this.desc = desc;
      this.ecus = ecus;
    }
  }

  private static String yamlStr(String s) {
    return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
  }

  private static String hex(byte[] b) {
    StringBuilder sb = new StringBuilder();
    for (byte x : b) sb.append(String.format("%02x", x));
    return sb.toString();
  }

  private static String sha256Hex(byte[] b) {
    try {
      return hex(MessageDigest.getInstance("SHA-256").digest(b));
    } catch (Exception e) {
      throw new IllegalStateException(e);
    }
  }
}
